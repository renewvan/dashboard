// Third-party notices: which packages ship, and the licence text each one asks to keep.
//
// Shared by the CLI (`scripts/generate-notices.ts`, run as `pnpm notices`) and the drift test
// (`src/lib/notices.test.ts`). Everything that touches the outside world (the `pnpm` call, reading
// licence files) is separate from `collectNotices`, the pure part that decides the groups.
import { execFileSync } from 'node:child_process'
import { readdirSync, readFileSync, realpathSync } from 'node:fs'
import { join } from 'node:path'

export interface NoticePackage {
  name: string
  version: string
}

export interface NoticeGroup {
  licence: string
  text: string
  packages: NoticePackage[]
}

export interface Notices {
  groups: NoticeGroup[]
}

/** One installed copy of a production package, as `pnpm licenses list --prod` reports it. */
export interface ProductionPackage {
  name: string
  version: string
  /** The package's `license` field: an SPDX id or expression. */
  licence: string
  /** Where the package is installed; only ever read from, never written to the output. */
  dir: string
}

const excludeFile = 'scripts/notices-exclude.json'
const includeFile = 'scripts/notices-include.json'
const fallbackDir = 'scripts/notices-fallback'

// ---------------------------------------------------------------------------------------------
// Pure part
// ---------------------------------------------------------------------------------------------

/** Exclude entries are exact names, or a prefix ending in `*` (platform binaries differ per OS). */
export function isExcluded(name: string, patterns: readonly string[]): boolean {
  return patterns.some((p) => (p.endsWith('*') ? name.startsWith(p.slice(0, -1)) : name === p))
}

export interface CollectInput {
  packages: readonly ProductionPackage[]
  exclude: readonly string[]
  /** Licence text of the packages that have no licence file on disk, by package name. */
  fallbacks: Readonly<Record<string, string>>
  /** The licence text found in an installed package's folder, or null when it has none. */
  readLicence: (dir: string) => string | null
}

const versions = new Intl.Collator('en', { numeric: true })

function byName(a: NoticePackage, b: NoticePackage): number {
  if (a.name !== b.name) return a.name < b.name ? -1 : 1
  return versions.compare(a.version, b.version)
}

function normalise(text: string): string {
  return text.replace(/\r\n?/g, '\n').trim()
}

/**
 * Groups the shipped packages by distinct licence text. A group's `licence` is the SPDX label of
 * its packages; if byte-identical texts ever carry different labels they share one group and the
 * labels are joined with ` / `.
 */
export function collectNotices({
  packages,
  exclude,
  fallbacks,
  readLicence,
}: CollectInput): Notices {
  const byText = new Map<string, { licences: Set<string>; packages: NoticePackage[] }>()
  const missing: string[] = []

  for (const pkg of packages) {
    if (isExcluded(pkg.name, exclude)) continue
    const onDisk = readLicence(pkg.dir)
    const raw = onDisk ?? fallbacks[pkg.name]
    if (raw === undefined || normalise(raw) === '') {
      missing.push(`${pkg.name}@${pkg.version}`)
      continue
    }
    const text = normalise(raw)
    let group = byText.get(text)
    if (!group) {
      group = { licences: new Set(), packages: [] }
      byText.set(text, group)
    }
    group.licences.add(pkg.licence)
    group.packages.push({ name: pkg.name, version: pkg.version })
  }

  if (missing.length > 0) {
    throw new Error(
      `No licence text for ${missing.join(', ')}: it ships (or is not in ${excludeFile}) and has no ` +
        `licence file on disk. Add its real upstream text as ${fallbackDir}/<name>.txt (with an ` +
        `entry in ${fallbackDir}/sources.json), or add it to ${excludeFile} if it does not ship.`,
    )
  }

  const groups: NoticeGroup[] = [...byText].map(([text, g]) => ({
    licence: [...g.licences].sort().join(' / '),
    text,
    packages: [...new Map(g.packages.map((p) => [`${p.name}@${p.version}`, p])).values()].sort(
      byName,
    ),
  }))
  groups.sort((a, b) => {
    if (a.licence !== b.licence) return a.licence < b.licence ? -1 : 1
    return byName(a.packages[0], b.packages[0])
  })
  return { groups }
}

function quote(value: string): string {
  return `'${value.replace(/[\\']/g, '\\$&')}'`
}

/**
 * The text of `src/data/notices.generated.ts`, already in the shape `vp fmt` leaves unchanged
 * (the licence texts sit in template literals, which the formatter does not touch).
 */
export function renderNoticesModule(notices: Notices): string {
  const out: string[] = [
    '// Generated by `pnpm notices` (scripts/generate-notices.ts). Do not edit by hand: change a',
    '// dependency or scripts/notices-exclude.json, then regenerate. src/lib/notices.test.ts fails',
    '// when this file is out of date.',
    '',
    'export interface NoticePackage {',
    '  name: string',
    '  version: string',
    '}',
    '',
    'export interface NoticeGroup {',
    '  licence: string',
    '  text: string',
    '  packages: NoticePackage[]',
    '}',
    '',
    'export const notices: { groups: NoticeGroup[] } = {',
    '  groups: [',
  ]
  for (const group of notices.groups) {
    const text = group.text.replace(/[\\`]|\$\{/g, '\\$&')
    out.push('    {', `      licence: ${quote(group.licence)},`)
    out.push(`      text: \`${text}\`,`)
    const entries = group.packages.map(
      (p) => `{ name: ${quote(p.name)}, version: ${quote(p.version)} }`,
    )
    // The formatter keeps a lone entry on the property's line when it fits in 100 columns.
    const oneLine = `      packages: [${entries[0]}],`
    if (entries.length === 1 && oneLine.length <= 100) {
      out.push(oneLine)
    } else {
      out.push('      packages: [', ...entries.map((e) => `        ${e},`), '      ],')
    }
    out.push('    },')
  }
  out.push('  ],', '}', '')
  return out.join('\n')
}

// ---------------------------------------------------------------------------------------------
// Outside world: pnpm, the installed packages, the checked-in lists
// ---------------------------------------------------------------------------------------------

interface PnpmLicenceEntry {
  name: string
  versions: string[]
  paths: string[]
  license: string
}

/**
 * `pnpm licenses list --prod --json`: the production dependency tree from the lockfile and the
 * installed packages, no network. Falls back to `vp pm` where only the Vite+ CLI is on the PATH.
 */
function runPnpmLicences(root: string): string {
  const args = ['licenses', 'list', '--prod', '--json']
  const attempts: [string, string[]][] = [
    ['pnpm', args],
    ['vp', ['pm', ...args]],
  ]
  const errors: string[] = []
  for (const [command, commandArgs] of attempts) {
    try {
      return execFileSync(command, commandArgs, {
        cwd: root,
        encoding: 'utf8',
        maxBuffer: 64 * 1024 * 1024,
        stdio: ['ignore', 'pipe', 'pipe'],
      })
    } catch (error) {
      errors.push(`${command}: ${error instanceof Error ? error.message : String(error)}`)
    }
  }
  throw new Error(
    `Could not list production licences (is node_modules installed?)\n${errors.join('\n')}`,
  )
}

/** One entry per installed copy; the version is read from the folder, so a path never mislabels it. */
export function listProductionPackages(root: string): ProductionPackage[] {
  const byLicence = JSON.parse(runPnpmLicences(root)) as Record<string, PnpmLicenceEntry[]>
  const found: ProductionPackage[] = []
  for (const [licence, entries] of Object.entries(byLicence)) {
    for (const entry of entries) {
      for (const dir of entry.paths) {
        const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')) as {
          version: string
        }
        found.push({ name: entry.name, version: manifest.version, licence, dir })
      }
    }
  }
  return found
}

/** A package that ships although it is not a production dependency, and why. */
export interface IncludedPackage {
  name: string
  reason: string
}

/** The checked-in include list: packages that end up in the build but `--prod` does not report. */
export function readIncludeList(root: string): IncludedPackage[] {
  const file = JSON.parse(readFileSync(join(root, includeFile), 'utf8')) as {
    packages: IncludedPackage[]
  }
  return file.packages
}

/** An installed package, resolved from `<root>/node_modules/<name>` (symlinks followed). */
function resolveInstalled(root: string, name: string): ProductionPackage {
  const dir = join(root, 'node_modules', name)
  let manifest: { version: string; license?: string }
  try {
    manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  } catch {
    throw new Error(
      `${includeFile} lists ${name}, which is not installed in node_modules (is it still a dependency?)`,
    )
  }
  if (!manifest.license) throw new Error(`${name} declares no "license" in its package.json`)
  return { name, version: manifest.version, licence: manifest.license, dir: realpathSync(dir) }
}

/**
 * Everything that ships: the production dependencies plus the packages in the include list, resolved
 * from `node_modules`. One entry per name and version; an included package that the exclude list
 * would drop is a contradiction and throws.
 */
export function listShippedPackages(root: string): ProductionPackage[] {
  const exclude = readExcludeList(root)
  const shipped = listProductionPackages(root)
  const known = new Set(shipped.map((p) => `${p.name}@${p.version}`))
  for (const { name } of readIncludeList(root)) {
    if (isExcluded(name, exclude)) {
      throw new Error(`${name} is in both ${includeFile} and ${excludeFile}: it cannot be both`)
    }
    const pkg = resolveInstalled(root, name)
    if (!known.has(`${pkg.name}@${pkg.version}`)) shipped.push(pkg)
  }
  return shipped
}

const licenceFile = /^(licen[sc]e|copying)(?![a-z])/i

/**
 * The licence file(s) in a package folder (`LICENSE`, `LICENCE.md`, `LICENSE-MIT`, `COPYING`...).
 * Several are joined in name order. Null when there is none.
 */
export function readLicenceFile(dir: string): string | null {
  const files = readdirSync(dir)
    .filter((f) => licenceFile.test(f))
    .sort()
  if (files.length === 0) return null
  return files.map((f) => normalise(readFileSync(join(dir, f), 'utf8'))).join('\n\n')
}

/** The checked-in exclude list, flattened. Each group carries the reason, for review. */
export function readExcludeList(root: string): string[] {
  const file = JSON.parse(readFileSync(join(root, excludeFile), 'utf8')) as {
    groups: { reason: string; packages: string[] }[]
  }
  return file.groups.flatMap((g) => g.packages)
}

/** Checked-in licence texts for shipped packages with no licence file on disk, by package name. */
export function readFallbacks(root: string): Record<string, string> {
  const sources = JSON.parse(
    readFileSync(join(root, fallbackDir, 'sources.json'), 'utf8'),
  ) as Record<string, unknown>
  return Object.fromEntries(
    Object.keys(sources).map((name) => [
      name,
      readFileSync(join(root, fallbackDir, `${name}.txt`), 'utf8'),
    ]),
  )
}

/** The whole pipeline, as the CLI runs it. */
export function generateNotices(root: string): Notices {
  return collectNotices({
    packages: listShippedPackages(root),
    exclude: readExcludeList(root),
    fallbacks: readFallbacks(root),
    readLicence: readLicenceFile,
  })
}
